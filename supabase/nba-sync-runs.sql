-- Histórico técnico da sincronização NBA
create table if not exists public.nba_sync_runs (
  id bigint generated by default as identity primary key,
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  mode text not null check (mode in ('fast','full')),
  status text not null default 'running' check (status in ('running','success','error')),
  games_upserted integer not null default 0,
  source text,
  error_message text
);

alter table public.nba_sync_runs enable row level security;
revoke all on public.nba_sync_runs from anon, authenticated;
