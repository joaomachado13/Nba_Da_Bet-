-- Bolão NBA — sincronização automática de calendário, status e placares
-- Aplicado no Supabase Nba_da_bet em 2026-10-22.
-- Fonte operacional de placares: ESPN scoreboard público.
-- O NBA CDN oficial permanece como referência de calendário, mas bloqueia
-- chamadas server-to-server do ambiente Supabase (HTTP 403).

create extension if not exists http with schema extensions;

create table if not exists private.nba_sync_log (
  id bigint generated by default as identity primary key,
  sync_type text not null,
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  round_date_from date,
  round_date_to date,
  games_processed integer not null default 0,
  error_text text
);

create or replace function private.sync_nba_date(p_round_date date)
returns integer
language plpgsql
set search_path = public, private, extensions, pg_temp
as $$
declare
  v_response extensions.http_response;
  v_payload jsonb;
  v_event jsonb;
  v_comp jsonb;
  v_away jsonb;
  v_home jsonb;
  v_status text;
  v_status_name text;
  v_state text;
  v_completed boolean;
  v_away_code text;
  v_home_code text;
  v_away_name text;
  v_home_name text;
  v_away_record text;
  v_home_record text;
  v_away_score integer;
  v_home_score integer;
  v_start_at timestamptz;
  v_arena text;
  v_broadcast text;
  v_existing_id text;
  v_insert_id text;
  v_count integer := 0;
  v_url text;
begin
  v_url := 'https://site.api.espn.com/apis/site/v2/sports/basketball/nba/scoreboard?dates='
    || to_char(p_round_date, 'YYYYMMDD');

  v_response := extensions.http_get(v_url);

  if v_response.status <> 200 then
    raise exception 'NBA scoreboard HTTP % for %', v_response.status, p_round_date;
  end if;

  v_payload := v_response.content::jsonb;

  for v_event in
    select value from jsonb_array_elements(coalesce(v_payload->'events', '[]'::jsonb))
  loop
    v_comp := v_event->'competitions'->0;

    select value into v_away
    from jsonb_array_elements(coalesce(v_comp->'competitors', '[]'::jsonb))
    where value->>'homeAway' = 'away'
    limit 1;

    select value into v_home
    from jsonb_array_elements(coalesce(v_comp->'competitors', '[]'::jsonb))
    where value->>'homeAway' = 'home'
    limit 1;

    if v_away is null or v_home is null then
      continue;
    end if;

    v_away_code := upper(v_away->'team'->>'abbreviation');
    v_home_code := upper(v_home->'team'->>'abbreviation');
    v_away_name := coalesce(v_away->'team'->>'displayName', v_away_code);
    v_home_name := coalesce(v_home->'team'->>'displayName', v_home_code);

    select coalesce(
      (select rr->>'summary'
       from jsonb_array_elements(coalesce(v_away->'records','[]'::jsonb)) rr
       where rr->>'type' = 'total'
       limit 1),
      '0-0'
    ) into v_away_record;

    select coalesce(
      (select rr->>'summary'
       from jsonb_array_elements(coalesce(v_home->'records','[]'::jsonb)) rr
       where rr->>'type' = 'total'
       limit 1),
      '0-0'
    ) into v_home_record;

    v_state := coalesce(v_event->'status'->'type'->>'state', 'pre');
    v_status_name := upper(coalesce(v_event->'status'->'type'->>'name', ''));
    v_completed := coalesce((v_event->'status'->'type'->>'completed')::boolean, false);

    v_status := case
      when v_status_name like '%POSTPON%' then 'postponed'
      when v_status_name like '%CANCEL%' then 'cancelled'
      when v_state = 'in' then 'live'
      when v_state = 'post' and v_completed then 'final'
      else 'scheduled'
    end;

    v_start_at := (v_event->>'date')::timestamptz;
    v_arena := nullif(v_comp->'venue'->>'fullName', '');
    v_broadcast := nullif(v_comp->'broadcasts'->0->'names'->>0, '');

    if v_status in ('live','final') then
      v_away_score := nullif(v_away->>'score','')::integer;
      v_home_score := nullif(v_home->>'score','')::integer;
    else
      v_away_score := null;
      v_home_score := null;
    end if;

    select g.id into v_existing_id
    from public.games g
    where g.round_date = p_round_date
      and g.away_team_code = v_away_code
      and g.home_team_code = v_home_code
    order by g.created_at
    limit 1;

    if v_existing_id is not null then
      update public.games
      set
        start_at = v_start_at,
        status = v_status,
        away_team_name = v_away_name,
        away_record = v_away_record,
        home_team_name = v_home_name,
        home_record = v_home_record,
        away_score = v_away_score,
        home_score = v_home_score,
        arena = coalesce(v_arena, arena),
        broadcast = coalesce(v_broadcast, broadcast),
        external_updated_at = now(),
        updated_at = now()
      where id = v_existing_id;
    else
      v_insert_id := v_event->>'id';

      if exists (select 1 from public.games where id = v_insert_id) then
        v_insert_id := 'espn:' || v_insert_id || ':' || to_char(p_round_date,'YYYYMMDD');
      end if;

      insert into public.games (
        id, round_date, start_at, status,
        away_team_code, away_team_name, away_record, away_form,
        home_team_code, home_team_name, home_record, home_form,
        away_score, home_score, arena, broadcast,
        external_updated_at
      ) values (
        v_insert_id, p_round_date, v_start_at, v_status,
        v_away_code, v_away_name, v_away_record, '[]'::jsonb,
        v_home_code, v_home_name, v_home_record, '[]'::jsonb,
        v_away_score, v_home_score, v_arena, v_broadcast,
        now()
      );
    end if;

    v_existing_id := null;
    v_count := v_count + 1;
  end loop;

  return v_count;
end;
$$;

create or replace function private.sync_nba_window(p_start_date date, p_days integer default 11)
returns jsonb
language plpgsql
set search_path = public, private, extensions, pg_temp
as $$
declare
  i integer;
  v_total integer := 0;
  v_count integer;
  v_errors text := '';
  v_log_id bigint;
  v_date date;
begin
  insert into private.nba_sync_log(sync_type, round_date_from, round_date_to)
  values ('window', p_start_date, p_start_date + greatest(p_days - 1, 0))
  returning id into v_log_id;

  for i in 0..greatest(p_days - 1, 0)
  loop
    v_date := p_start_date + i;
    begin
      v_count := private.sync_nba_date(v_date);
      v_total := v_total + v_count;
    exception when others then
      v_errors := v_errors || case when v_errors='' then '' else E'\n' end
        || v_date::text || ': ' || sqlerrm;
    end;
  end loop;

  update private.nba_sync_log
  set finished_at = now(),
      games_processed = v_total,
      error_text = nullif(v_errors,'')
  where id = v_log_id;

  return jsonb_build_object(
    'from', p_start_date,
    'days', p_days,
    'games_processed', v_total,
    'errors', nullif(v_errors,'')
  );
end;
$$;

create or replace function private.sync_nba_current_round()
returns jsonb
language plpgsql
set search_path = public, private, extensions, pg_temp
as $$
declare
  v_round_date date;
  v_should_sync boolean;
  v_count integer := 0;
  v_log_id bigint;
  v_error text;
begin
  v_round_date := (
    (now() at time zone 'America/Sao_Paulo') - interval '6 hours'
  )::date;

  select exists (
    select 1
    from public.games g
    where g.round_date = v_round_date
      and g.status not in ('postponed','cancelled')
      and (
        g.status = 'live'
        or g.start_at between now() - interval '5 hours' and now() + interval '8 hours'
      )
  ) into v_should_sync;

  if not v_should_sync then
    return jsonb_build_object('round_date', v_round_date, 'skipped', true);
  end if;

  insert into private.nba_sync_log(sync_type, round_date_from, round_date_to)
  values ('current_round', v_round_date, v_round_date)
  returning id into v_log_id;

  begin
    v_count := private.sync_nba_date(v_round_date);
  exception when others then
    v_error := sqlerrm;
  end;

  update private.nba_sync_log
  set finished_at = now(),
      games_processed = v_count,
      error_text = v_error
  where id = v_log_id;

  if v_error is not null then
    raise exception '%', v_error;
  end if;

  return jsonb_build_object(
    'round_date', v_round_date,
    'skipped', false,
    'games_processed', v_count
  );
end;
$$;

revoke all on function private.sync_nba_date(date) from public, anon, authenticated;
revoke all on function private.sync_nba_window(date, integer) from public, anon, authenticated;
revoke all on function private.sync_nba_current_round() from public, anon, authenticated;

-- pg_cron usa UTC.
-- Atualiza a rodada atual a cada 5 min, mas a função só chama a fonte externa
-- quando existe jogo ao vivo ou próximo do horário.
select cron.schedule(
  'nba-current-round-5min',
  '*/5 * * * *',
  'select private.sync_nba_current_round();'
);

-- 12:05 UTC = 09:05 BRT. Mantém hoje + 10 dias sempre abastecidos.
select cron.schedule(
  'nba-schedule-daily',
  '5 12 * * *',
  $$select private.sync_nba_window(
      (now() at time zone 'America/Sao_Paulo')::date,
      11
    );$$
);
