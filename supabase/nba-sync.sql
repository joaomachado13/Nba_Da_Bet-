-- Bolão NBA — sincronização automática adaptativa de calendário, status e placares
-- Fonte: ESPN scoreboard público.
-- Estratégia: 5 min durante jogo normal; 1 min nos últimos 5:00 do 4º período/OT.
-- O cron roda a cada minuto, mas a função decide quando realmente chamar a ESPN.

create extension if not exists http with schema extensions;

alter table public.games add column if not exists period integer;
alter table public.games add column if not exists clock_display text;
alter table public.games add column if not exists clock_seconds integer;

create or replace function private.normalize_nba_team_code(p_code text)
returns text
language sql
immutable
strict
set search_path = pg_catalog
as $$
  select case upper(trim(p_code))
    when 'NY' then 'NYK'
    when 'WSH' then 'WAS'
    when 'SA' then 'SAS'
    when 'NO' then 'NOP'
    when 'GS' then 'GSW'
    when 'UTAH' then 'UTA'
    else upper(trim(p_code))
  end;
$$;

revoke all on function private.normalize_nba_team_code(text) from public, anon, authenticated;

create table if not exists private.nba_sync_log (
  id bigint generated by default as identity primary key,
  sync_type text not null,
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  round_date_from date,
  round_date_to date,
  games_processed integer not null default 0,
  error_text text
);

create or replace function private.clock_to_seconds(p_clock text)
returns integer
language plpgsql
immutable
strict
set search_path = pg_catalog
as $$
declare
  v_parts text[];
begin
  if trim(p_clock) = '' then return null; end if;
  v_parts := string_to_array(trim(p_clock), ':');
  if array_length(v_parts, 1) = 2 then
    return greatest(0, floor(v_parts[1]::numeric * 60 + v_parts[2]::numeric)::integer);
  end if;
  return null;
exception when others then
  return null;
end;
$$;

revoke all on function private.clock_to_seconds(text) from public, anon, authenticated;

create or replace function private.sync_nba_date(p_round_date date)
returns integer
language plpgsql
set search_path = public, private, extensions, pg_temp
as $$
declare
  v_response extensions.http_response;
  v_payload jsonb;
  v_event jsonb;
  v_comp jsonb;
  v_away jsonb;
  v_home jsonb;
  v_status text;
  v_status_name text;
  v_state text;
  v_completed boolean;
  v_away_code text;
  v_home_code text;
  v_away_name text;
  v_home_name text;
  v_away_record text;
  v_home_record text;
  v_away_score integer;
  v_home_score integer;
  v_period integer;
  v_clock_display text;
  v_clock_seconds integer;
  v_start_at timestamptz;
  v_arena text;
  v_broadcast text;
  v_existing_id text;
  v_insert_id text;
  v_count integer := 0;
  v_url text;
begin
  v_url := 'https://site.api.espn.com/apis/site/v2/sports/basketball/nba/scoreboard?dates='
    || to_char(p_round_date, 'YYYYMMDD');

  v_response := extensions.http_get(v_url);

  if v_response.status <> 200 then
    raise exception 'NBA scoreboard HTTP % for %', v_response.status, p_round_date;
  end if;

  v_payload := v_response.content::jsonb;

  for v_event in
    select value from jsonb_array_elements(coalesce(v_payload->'events', '[]'::jsonb))
  loop
    v_comp := v_event->'competitions'->0;

    select value into v_away
    from jsonb_array_elements(coalesce(v_comp->'competitors', '[]'::jsonb))
    where value->>'homeAway' = 'away'
    limit 1;

    select value into v_home
    from jsonb_array_elements(coalesce(v_comp->'competitors', '[]'::jsonb))
    where value->>'homeAway' = 'home'
    limit 1;

    if v_away is null or v_home is null then
      continue;
    end if;

    v_away_code := private.normalize_nba_team_code(v_away->'team'->>'abbreviation');
    v_home_code := private.normalize_nba_team_code(v_home->'team'->>'abbreviation');
    v_away_name := coalesce(v_away->'team'->>'displayName', v_away_code);
    v_home_name := coalesce(v_home->'team'->>'displayName', v_home_code);

    select coalesce(
      (select rr->>'summary'
       from jsonb_array_elements(coalesce(v_away->'records','[]'::jsonb)) rr
       where rr->>'type' = 'total'
       limit 1),
      '0-0'
    ) into v_away_record;

    select coalesce(
      (select rr->>'summary'
       from jsonb_array_elements(coalesce(v_home->'records','[]'::jsonb)) rr
       where rr->>'type' = 'total'
       limit 1),
      '0-0'
    ) into v_home_record;

    v_state := coalesce(v_event->'status'->'type'->>'state', 'pre');
    v_status_name := upper(coalesce(v_event->'status'->'type'->>'name', ''));
    v_completed := coalesce((v_event->'status'->'type'->>'completed')::boolean, false);

    v_status := case
      when v_status_name like '%POSTPON%' then 'postponed'
      when v_status_name like '%CANCEL%' then 'cancelled'
      when v_state = 'in' then 'live'
      when v_state = 'post' and v_completed then 'final'
      else 'scheduled'
    end;

    v_period := nullif(v_event->'status'->>'period', '')::integer;
    v_clock_display := nullif(v_event->'status'->>'displayClock', '');
    v_clock_seconds := private.clock_to_seconds(v_clock_display);

    v_start_at := (v_event->>'date')::timestamptz;
    v_arena := nullif(v_comp->'venue'->>'fullName', '');
    v_broadcast := nullif(v_comp->'broadcasts'->0->'names'->>0, '');

    if v_status in ('live','final') then
      v_away_score := nullif(v_away->>'score','')::integer;
      v_home_score := nullif(v_home->>'score','')::integer;
    else
      v_away_score := null;
      v_home_score := null;
    end if;

    select g.id into v_existing_id
    from public.games g
    where g.round_date = p_round_date
      and private.normalize_nba_team_code(g.away_team_code) = v_away_code
      and private.normalize_nba_team_code(g.home_team_code) = v_home_code
    order by g.created_at
    limit 1;

    if v_existing_id is not null then
      update public.games
      set
        start_at = v_start_at,
        status = v_status,
        away_team_code = v_away_code,
        away_team_name = v_away_name,
        away_record = v_away_record,
        home_team_code = v_home_code,
        home_team_name = v_home_name,
        home_record = v_home_record,
        away_score = v_away_score,
        home_score = v_home_score,
        period = v_period,
        clock_display = v_clock_display,
        clock_seconds = v_clock_seconds,
        arena = coalesce(v_arena, arena),
        broadcast = coalesce(v_broadcast, broadcast),
        external_updated_at = now(),
        updated_at = now()
      where id = v_existing_id;
    else
      v_insert_id := v_event->>'id';

      if exists (select 1 from public.games where id = v_insert_id) then
        v_insert_id := 'espn:' || v_insert_id || ':' || to_char(p_round_date,'YYYYMMDD');
      end if;

      insert into public.games (
        id, round_date, start_at, status,
        away_team_code, away_team_name, away_record, away_form,
        home_team_code, home_team_name, home_record, home_form,
        away_score, home_score, period, clock_display, clock_seconds,
        arena, broadcast, external_updated_at
      ) values (
        v_insert_id, p_round_date, v_start_at, v_status,
        v_away_code, v_away_name, v_away_record, '[]'::jsonb,
        v_home_code, v_home_name, v_home_record, '[]'::jsonb,
        v_away_score, v_home_score, v_period, v_clock_display, v_clock_seconds,
        v_arena, v_broadcast, now()
      );
    end if;

    v_existing_id := null;
    v_count := v_count + 1;
  end loop;

  return v_count;
end;
$$;

create or replace function private.sync_nba_window(p_start_date date, p_days integer default 11)
returns jsonb
language plpgsql
set search_path = public, private, extensions, pg_temp
as $$
declare
  i integer;
  v_total integer := 0;
  v_count integer;
  v_errors text := '';
  v_log_id bigint;
  v_date date;
begin
  insert into private.nba_sync_log(sync_type, round_date_from, round_date_to)
  values ('window', p_start_date, p_start_date + greatest(p_days - 1, 0))
  returning id into v_log_id;

  for i in 0..greatest(p_days - 1, 0)
  loop
    v_date := p_start_date + i;
    begin
      v_count := private.sync_nba_date(v_date);
      v_total := v_total + v_count;
    exception when others then
      v_errors := v_errors || case when v_errors='' then '' else E'\n' end
        || v_date::text || ': ' || sqlerrm;
    end;
  end loop;

  update private.nba_sync_log
  set finished_at = now(),
      games_processed = v_total,
      error_text = nullif(v_errors,'')
  where id = v_log_id;

  return jsonb_build_object(
    'from', p_start_date,
    'days', p_days,
    'games_processed', v_total,
    'errors', nullif(v_errors,'')
  );
end;
$$;

create or replace function private.sync_nba_current_round()
returns jsonb
language plpgsql
set search_path = public, private, extensions, pg_temp
as $$
declare
  v_round_date date;
  v_due boolean := false;
  v_fast_mode boolean := false;
  v_interval interval;
  v_last_sync timestamptz;
  v_count integer := 0;
  v_log_id bigint;
  v_error text;
begin
  v_round_date := (
    (now() at time zone 'America/Sao_Paulo') - interval '6 hours'
  )::date;

  select exists (
    select 1
    from public.games g
    where g.round_date = v_round_date
      and g.status not in ('final','postponed','cancelled')
      and (
        g.status = 'live'
        or (g.status = 'scheduled' and g.start_at <= now())
      )
  ) into v_due;

  if not v_due then
    return jsonb_build_object(
      'round_date', v_round_date,
      'skipped', true,
      'reason', 'no_game_due'
    );
  end if;

  select exists (
    select 1
    from public.games g
    where g.round_date = v_round_date
      and g.status = 'live'
      and (
        coalesce(g.period, 0) > 4
        or (g.period = 4 and coalesce(g.clock_seconds, 9999) <= 300)
      )
  ) into v_fast_mode;

  v_interval := case when v_fast_mode then interval '1 minute' else interval '5 minutes' end;

  select max(l.finished_at) into v_last_sync
  from private.nba_sync_log l
  where l.sync_type = 'current_round'
    and l.round_date_from = v_round_date
    and l.error_text is null;

  if v_last_sync is not null and now() - v_last_sync < v_interval then
    return jsonb_build_object(
      'round_date', v_round_date,
      'skipped', true,
      'reason', case when v_fast_mode then 'fast_interval' else 'normal_interval' end,
      'mode', case when v_fast_mode then '1m' else '5m' end
    );
  end if;

  insert into private.nba_sync_log(sync_type, round_date_from, round_date_to)
  values ('current_round', v_round_date, v_round_date)
  returning id into v_log_id;

  begin
    v_count := private.sync_nba_date(v_round_date);
  exception when others then
    v_error := sqlerrm;
  end;

  update private.nba_sync_log
  set finished_at = now(),
      games_processed = v_count,
      error_text = v_error
  where id = v_log_id;

  if v_error is not null then
    raise exception '%', v_error;
  end if;

  return jsonb_build_object(
    'round_date', v_round_date,
    'skipped', false,
    'mode', case when v_fast_mode then '1m' else '5m' end,
    'games_processed', v_count
  );
end;
$$;

revoke all on function private.sync_nba_date(date) from public, anon, authenticated;
revoke all on function private.sync_nba_window(date, integer) from public, anon, authenticated;
revoke all on function private.sync_nba_current_round() from public, anon, authenticated;

-- Limpeza defensiva e genérica de partidas equivalentes.
-- Mantém preferencialmente o ID 002... já usado pelo bolão e migra qualquer
-- palpite ligado a uma cópia antes de removê-la.
drop table if exists pg_temp.nba_game_merge;

create temporary table nba_game_merge on commit drop as
with ranked as (
  select
    g.id,
    first_value(g.id) over (
      partition by
        g.round_date,
        private.normalize_nba_team_code(g.away_team_code),
        private.normalize_nba_team_code(g.home_team_code)
      order by
        case when g.id like '002%' then 0 else 1 end,
        g.created_at,
        g.id
    ) as canonical_id
  from public.games g
)
select id as duplicate_id, canonical_id
from ranked
where id <> canonical_id;

delete from public.predictions p
using pg_temp.nba_game_merge m
where p.game_id = m.duplicate_id
  and exists (
    select 1
    from public.predictions keep
    where keep.user_id = p.user_id
      and keep.game_id = m.canonical_id
  );

update public.predictions p
set game_id = m.canonical_id,
    picked_team_code = private.normalize_nba_team_code(p.picked_team_code),
    updated_at = now()
from pg_temp.nba_game_merge m
where p.game_id = m.duplicate_id;

delete from public.games g
using pg_temp.nba_game_merge m
where g.id = m.duplicate_id;

update public.games
set away_team_code = private.normalize_nba_team_code(away_team_code),
    home_team_code = private.normalize_nba_team_code(home_team_code),
    updated_at = now();

update public.predictions
set picked_team_code = private.normalize_nba_team_code(picked_team_code),
    updated_at = now();

create unique index if not exists games_round_match_unique
  on public.games(round_date, away_team_code, home_team_code);

-- pg_cron roda em UTC. O job desperta a cada minuto, mas a função só consulta
-- a ESPN quando necessário: 5 min no jogo normal e 1 min na reta final.
select cron.unschedule(jobid)
from cron.job
where jobname in ('nba-current-round-5min','nba-current-round-adaptive');

select cron.schedule(
  'nba-current-round-adaptive',
  '* * * * *',
  'select private.sync_nba_current_round();'
);

-- 12:05 UTC = 09:05 BRT. Mantém hoje + 10 dias abastecidos.
select cron.unschedule(jobid)
from cron.job
where jobname = 'nba-schedule-daily';

select cron.schedule(
  'nba-schedule-daily',
  '5 12 * * *',
  $$select private.sync_nba_window(
      (now() at time zone 'America/Sao_Paulo')::date,
      11
    );$$
);
