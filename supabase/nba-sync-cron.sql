-- Automação NBA do Bolão NBA
-- Vercel hospeda o frontend; Supabase Cron mantém calendário, status e placares atualizados.

create extension if not exists pg_cron with schema pg_catalog;
create extension if not exists pg_net with schema extensions;

create table if not exists public.nba_sync_runs (
  id bigint generated by default as identity primary key,
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  mode text not null check (mode in ('fast','full')),
  status text not null default 'running' check (status in ('running','success','error')),
  games_upserted integer not null default 0,
  source text,
  error_message text
);
alter table public.nba_sync_runs enable row level security;
revoke all on public.nba_sync_runs from anon, authenticated;

create table if not exists public.nba_sync_config (
  id smallint primary key check (id = 1),
  sync_secret text not null,
  updated_at timestamptz not null default now()
);
alter table public.nba_sync_config enable row level security;
revoke all on public.nba_sync_config from anon, authenticated;

insert into public.nba_sync_config (id, sync_secret)
values (1, encode(gen_random_bytes(32), 'hex'))
on conflict (id) do nothing;

select cron.schedule(
  'nba-sync-fast',
  '*/5 * * * *',
  $cron$
  select net.http_post(
    url := 'https://wueaswmbujgitfxydphh.supabase.co/functions/v1/nba-sync',
    headers := jsonb_build_object(
      'Content-Type','application/json',
      'x-sync-secret',(select sync_secret from public.nba_sync_config where id=1)
    ),
    body := '{"mode":"fast"}'::jsonb,
    timeout_milliseconds := 15000
  );
  $cron$
);

